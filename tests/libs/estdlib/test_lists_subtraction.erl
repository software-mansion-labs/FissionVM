-module(test_lists_subtraction).

-export([test/0]).

test() ->
    Tests = [
        {[1, 2, 3], [1], [2, 3]},
        {[1, 2, 3], [3], [1, 2]},
        {[1, 2, 3], [5], [1, 2, 3]},
        {[1, 2, 2, 3], [2], [1, 2, 3]},
        {[1, 2, 3, 4], [2, 2], [1, 3, 4]},
        {["a", 1, "b", 2], ["a", 2], [1, "b"]},
        {[1, 2, 3], [1, 2, 3, 4, 5], []},
        {[1, 2, 3], [], [1, 2, 3]},
        {[], [1, 2, 3], []}
    ],

    run_tests(Tests).

run_tests(Tests) ->
    [Expected = A -- B || {A, B, Expected} <- Tests],
    ok.
